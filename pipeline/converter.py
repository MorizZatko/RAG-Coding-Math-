import os
import uuid
import gc
import fitz
import re
import hashlib
import torch
from pathlib import Path
from PIL import ImageOps
from docling.document_converter import DocumentConverter, PdfFormatOption
from docling.datamodel.base_models import InputFormat
from docling.datamodel.pipeline_options import PdfPipelineOptions
from docling_core.types.doc import PictureItem
import ollama

MIN_IMAGE_SIDE = 175
GARBAGE_DIR = "garbage"
VISION_MODEL = "llava"
SKIP_CLASSES = {"logo", "icon", "signature", "stamp", "qr_code", "bar_code"}
MATH_PATTERNS = re.compile(
    r"("
    r"\b(Theorem|Lemma|Definition|Proof|Proposition|Corollary)\b"  
    r"|\([0-9]+\.[0-9]+\)"                                                 
    r"|\[[A-Za-z0-9,\s+-]+\]"                                               
    r")",
    re.IGNORECASE
)


def needs_formula_enchrichment(pdf_path: str, threshold: float = 2.0):
    """Determines, based on the first 16 pages, whether a document has a high formula density.
    
    Args:
        pdf_path (str): Path to PDF file.
        threshold (float): Threshold for formula density.

    Returns:
        bool: If document has high formula density or not.
    """
    try:
        doc = fitz.open(pdf_path)
        text = "".join([doc[i].get_text() for i in range(min(len(doc), 16))])
        doc.close()

        if not text:
            return False

        matches = len(MATH_PATTERNS.findall(text))
        density = (len(MATH_PATTERNS.findall(text)) / len(text)) * 1000
      
        print(f"DEBUG: Paper structure density for: '{pdf_path}': {density:.2f} (Treffer: {matches})")

        return density > threshold
    except Exception:
        return True


def _analyze_image_with_llava(img_path: str, context_page: str):
    """Sends extracted images to LLaVA to analyze their content.
    
    Args:
        img_path (str): Path to the image file.
        context_page (str): Context string containing page, figures and captions.

    Returns:
        F-String (str): Image description generated by LLaVA, or an empty string on failure.
    """
    try:
        result = ollama.chat(
            model=VISION_MODEL,
            messages=[{
                'role': 'user',
                'content': f"This image is from {context_page}. "
                            "Explain all axes, values, trends, and the core message clearly and concisely for an AI knowledge base.",
                'images': [img_path]
            }],
            options={"num_predict": 500, "temperature": 0.1},
            keep_alive="10m"
        )
    
        return result.get('message', {}).get('content', '')
    except Exception as e:
        print(f"DEBUG: LLaVA Error at {context_page}: {e}")
        return ""


def _pad_image(pil_image, img_path, padding: int = 25):
    """Adds a white border (padding) to the image and saves it."""
    pil_image = pil_image.convert("RGB")
    padded_image = ImageOps.expand(pil_image, border=padding, fill='white')
    padded_image.save(img_path)


def _picture_class(element):
    """Returns the best class name of the docling picture classifier, or None if unclassified."""
    for ann in getattr(element, "annotations", []):
        classes = getattr(ann, "predicted_classes", None)
        if classes:
            return classes[0].class_name
    return None


def _discard_image(pil_image, reason: str, page_num: int):
    """Saves a filtered picture into the garbage folder (reason in file name) so the filters can be checked."""
    os.makedirs(GARBAGE_DIR, exist_ok=True)
    name = f"{reason}_page{page_num}_{uuid.uuid4().hex[:6]}.png"
    pil_image.convert("RGB").save(os.path.join(GARBAGE_DIR, name))


def _unload_llava():
    """Removes LLaVA from VRAM to ensure enough space is available for new imports or chats."""
    try:
        ollama.generate(model=VISION_MODEL, prompt="", keep_alive=0)
        print("DEBUG: LLaVA succesfully removed from VRAM.")
    except Exception as e:
        print(f"DEBUG: LLaVA remove failed: {e}")


def _convert_pdf(file_bytes: bytes, file_name: str = "document", status_callback=None, padding: int = 25):
    """Converts PDFs, DOCXs and MD-files and requests LLaVA.

    Args:
        file_bytes (bytes): The binary content of the file to be converted.
        file_name (str, optional): The original file name. Defaults to "document".
        status_callback (callable, optional): Callback function to report status updates and progress. Defaults to None.
        padding (int, optional): Padding size applied to extracted images. Defaults to 25.

    Returns:
        tuple: A tuple containing:
            - doc: The parsed document object generated by Docling.
            - image_infos (list): A list of dictionaries with details for each processed image (page number, file path, LLaVA description, and caption).
    """
    unique_id = uuid.uuid4().hex[:8]

    suffix = Path(file_name).suffix.lower()
    if suffix not in (".pdf", ".docx", ".md"):
        suffix = ".pdf"

    temp_pdf_path = f"temp{unique_id}{suffix}"

    with open(temp_pdf_path, "wb") as f:
        f.write(file_bytes)

    should_enrich_formulas = needs_formula_enchrichment(temp_pdf_path)
    print(f"DEBUG: Formula enrichment activated for '{file_name}' | {should_enrich_formulas}")

    if status_callback:
        status_callback("text", 0.1, "Starts Docling parsing...")

    safe_file_name = "".join(c for c in file_name if c.isalnum() or c in (' ', '_', '-')).rstrip()
    if not safe_file_name:
        safe_file_name = "doc"
    img_dir = os.path.join("extracted_images", f"{safe_file_name}_{unique_id}")
    
    try:
        if status_callback:
            status_callback("text", 0.3, "Analyze document structure & layout...")

        pipeline_options = PdfPipelineOptions()
        pipeline_options.generate_picture_images = True
        pipeline_options.images_scale = 3.0
        pipeline_options.do_picture_classification = True
        pipeline_options.do_formula_enrichment = should_enrich_formulas

        converter = DocumentConverter(
            format_options={InputFormat.PDF: PdfFormatOption(pipeline_options=pipeline_options)}
        )
        conv_res = converter.convert(temp_pdf_path)
        doc = conv_res.document
        del converter, conv_res
        gc.collect()
        torch.cuda.empty_cache()
        if torch.cuda.is_available():
            free, total = torch.cuda.mem_get_info()
            print(f"DEBUG: VRAM after Docling: {(total - free) / 1024**3:.2f} GB used of {total / 1024**3:.1f} GB")

        if status_callback:
            status_callback("images", 0.3, "Looking for relevant plots & figures...")

        picture_elements = [element for element, _ in doc.iterate_items() if isinstance(element, PictureItem)]

        total_images = len(picture_elements)
        print(f"DEBUG: Docling hat {total_images} Bilder/Diagramme gefunden!")

        img_counter = 0
        image_infos = []
        seen_hashes = {}

        for element in picture_elements:
            # Render the picture element as an image
            try:
                pil_image = element.get_image(doc)
            except Exception:
                pil_image = None

            if not pil_image:
                continue

            page_num = element.prov[0].page_no if element.prov else 1
            try:
                caption = element.caption_text(doc)
            except Exception:
                caption = ""

            pic_class = _picture_class(element)
            print(f"DEBUG: Picture class: {pic_class}, size: {pil_image.size}, page: {page_num}")
            
            reason = None
            if min(pil_image.size) < MIN_IMAGE_SIDE:
                reason = "too_small"
            elif pic_class in SKIP_CLASSES:
                reason = f"class_{pic_class}"
            else:
                thumb = pil_image.convert("L").resize((32, 32))
                img_hash = hashlib.md5(thumb.tobytes()).hexdigest()
                seen_hashes[img_hash] = seen_hashes.get(img_hash, 0) + 1
                if seen_hashes[img_hash] > 2:
                    reason = "duplicate"

            if reason:
                print(f"DEBUG: Picture discarded ({reason}).")
                _discard_image(pil_image, reason, page_num)
                continue
 
            try:
                img_counter += 1

                if img_counter == 1:
                    os.makedirs(img_dir, exist_ok=True)
                        
                img_filename = f"fig{img_counter}_page{page_num}_{unique_id}.png"
                img_path = os.path.join(img_dir, img_filename)

                pil_image.convert("RGB").save(img_path)
                print(f"DEBUG: Bild {img_counter}/{total_images} gespeichert unter {img_path}. Starte jz LLaVA analyse...")

                if status_callback:
                    progress_val = 0.4 + (0.5 * (img_counter / max(1, total_images)))
                    status_callback("images", progress_val, f"Analyze figure {img_counter} of {total_images} via LLavA...", img_counter, total_images)

                description = _analyze_image_with_llava(img_path, f"Document Page {page_num} (Figure {img_counter}). Caption: {caption}")
                image_infos.append({"page": page_num, "path": img_path, "description": description, "caption": caption})

                print(f"DEBUG: LLaVA Analyse für Bild {img_counter} beendet.")

                _pad_image(pil_image, img_path, padding=padding)

            finally:
                del pil_image
                gc.collect()

        if status_callback:
            status_callback("text", 0.9, "Create final Markdown export...")

    except Exception as e:
        raise RuntimeError(f"Docling Error: {e}")
    finally:
        _unload_llava()
        if os.path.exists(temp_pdf_path):
            try:
                os.remove(temp_pdf_path)
            except Exception:
                pass

    if status_callback:
        status_callback("text", 1.0, "Succesfully converted and analyzed!")

    return doc, image_infos